-- Run this with `npm run db:setup`, or paste it into the Supabase SQL Editor.

create table if not exists public.products (
  pid integer generated by default as identity primary key,
  pname text not null,
  description text not null default '',
  price numeric(10, 2) not null default 0 check (price >= 0),
  qty integer not null default 0 check (qty >= 0)
);

create table if not exists public.users (
  uid integer generated by default as identity primary key,
  uname text not null,
  email text not null unique,
  password text not null
);

create table if not exists public.orders (
  oid integer generated by default as identity primary key,
  uid integer not null references public.users (uid) on delete cascade on update cascade,
  pid integer not null references public.products (pid) on delete cascade on update cascade,
  order_date timestamptz not null default now()
);

create index if not exists orders_uid_idx on public.orders (uid);
create index if not exists orders_pid_idx on public.orders (pid);

-- The server connects as the Postgres owner role, which bypasses RLS.
-- Enabling RLS without policies keeps these tables closed to the public API keys.
alter table public.products enable row level security;
alter table public.users enable row level security;
alter table public.orders enable row level security;
